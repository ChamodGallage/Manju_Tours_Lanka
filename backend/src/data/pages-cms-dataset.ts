// Runtime in-memory store synchronized across admin edits and public views
const runtimePages: PageRecord[] = [...DEFAULT_PAGES];
const runtimeSections: PageSectionItem[] = [...DEFAULT_PAGE_SECTIONS];

export function getRuntimePages(): PageRecord[] {
  return [...runtimePages].sort((a, b) => a.display_order - b.display_order);
}

export function getRuntimePage(keyOrSlug: string): PageRecord | undefined {
  return runtimePages.find((p) => p.page_key === keyOrSlug || p.slug === keyOrSlug);
}

export function updateRuntimePage(key: string, updates: Partial<PageRecord>): PageRecord | undefined {
  const index = runtimePages.findIndex((p) => p.page_key === key);
  if (index === -1) return undefined;
  runtimePages[index] = {
    ...runtimePages[index],
    ...updates,
    updated_at: new Date().toISOString(),
  };
  return runtimePages[index];
}

export function addRuntimePage(page: PageRecord): PageRecord {
  runtimePages.push({
    ...page,
    created_at: new Date().toISOString(),
    updated_at: new Date().toISOString(),
  });
  return page;
}

export function duplicateRuntimePage(sourceKey: string, newTitle: string, newSlug: string, newKey: string): PageRecord | null {
  const source = getRuntimePage(sourceKey);
  if (!source) return null;
  const newPage: PageRecord = {
    ...source,
    id: `page-${newKey}-${Date.now()}`,
    page_key: newKey,
    title: newTitle,
    slug: newSlug,
    status: "draft",
    is_published: false,
    display_order: runtimePages.length + 1,
    created_at: new Date().toISOString(),
    updated_at: new Date().toISOString(),
  };
  runtimePages.push(newPage);

  // Duplicate sections as well
  const sourceSections = runtimeSections.filter((s) => s.page_key === sourceKey);
  sourceSections.forEach((s, idx) => {
    runtimeSections.push({
      ...s,
      id: `sec-${newKey}-${idx}-${Date.now()}`,
      page_key: newKey,
      section_key: `${s.section_key}-copy`,
      updated_at: new Date().toISOString(),
    });
  });

  return newPage;
}

export function getRuntimeSections(pageKey: string): PageSectionItem[] {
  return runtimeSections
    .filter((s) => s.page_key === pageKey)
    .sort((a, b) => a.display_order - b.display_order);
}

export function upsertRuntimeSection(section: PageSectionItem): PageSectionItem {
  const index = runtimeSections.findIndex(
    (s) => (s.id && s.id === section.id) || (s.page_key === section.page_key && s.section_key === section.section_key)
  );

  const payload: PageSectionItem = {
    ...section,
    id: section.id || `sec-${section.page_key}-${Date.now()}`,
    updated_at: new Date().toISOString(),
  };

  if (index !== -1) {
    runtimeSections[index] = { ...runtimeSections[index], ...payload };
    return runtimeSections[index];
  } else {
    runtimeSections.push(payload);
    return payload;
  }
}

export function deleteRuntimeSection(id: string): boolean {
  const index = runtimeSections.findIndex((s) => s.id === id);
  if (index !== -1) {
    runtimeSections.splice(index, 1);
    return true;
  }
  return false;
}

export function reorderRuntimeSections(pageKey: string, orderedIds: string[]): PageSectionItem[] {
  orderedIds.forEach((id, index) => {
    const sec = runtimeSections.find((s) => s.id === id && s.page_key === pageKey);
    if (sec) {
      sec.display_order = index + 1;
      sec.updated_at = new Date().toISOString();
    }
  });
  return getRuntimeSections(pageKey);
}
