import { z } from "zod";

export const TourPackageSchema = z.object({
  id: z.string().optional(),
  title: z.string().min(3, "Title must be at least 3 characters").max(150),
  slug: z.string().min(2, "Slug must be at least 2 characters").max(100),
  tagline: z.string().max(200).optional().default(""),
  overview: z.string().optional().default(""),
  hero_image: z.string().min(1, "Hero image is required"),
  gallery_images: z.array(z.any()).optional().default([]),
  travel_style: z.string().optional().default("Private Chauffeur Guide"),
  destinations: z.array(z.string()).optional().default([]),
  duration_days: z.number().int().min(1).default(7),
  duration_nights: z.number().int().min(0).default(6),
  starting_price: z.string().optional().default("From $850 USD"),
  starting_price_numeric: z.number().optional().default(850),
  currency: z.string().optional().default("USD"),
  price_type: z.enum(["per_person", "per_group", "custom_quote"]).default("per_person"),
  min_travelers: z.number().int().min(1).default(1),
  max_travelers: z.number().int().min(1).default(8),
  inclusions: z.array(z.string()).optional().default([]),
  exclusions: z.array(z.string()).optional().default([]),
  itinerary: z.array(z.any()).optional().default([]),
  accommodation_details: z.string().optional().default(""),
  transport_details: z.string().optional().default(""),
  meals_included: z.string().optional().default(""),
  activities: z.array(z.string()).optional().default([]),
  optional_activities: z.array(z.string()).optional().default([]),
  suitable_for: z.array(z.string()).optional().default([]),
  booking_conditions: z.string().optional().default(""),
  cancellation_policy: z.string().optional().default(""),
  faqs: z.array(z.any()).optional().default([]),
  seo_title: z.string().optional().default(""),
  seo_description: z.string().optional().default(""),
  display_order: z.number().int().optional().default(0),
  is_featured: z.boolean().optional().default(false),
  is_published: z.boolean().optional().default(true),
});

export const TourPackageUpdateSchema = TourPackageSchema.partial();
